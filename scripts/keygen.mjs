// One-time, maintainer only: create the Ed25519 key that signs releases.
// The PRIVATE key stays on this computer (outside the repo); the PUBLIC key is written into
// updater/release-public-key.mjs and shipped to every updater. Back the private key up: without
// it no further automatic updates can be published (every updater would need a manual update).
import { generateKeyPairSync } from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

export const KEY_PATH =
  process.env.NCLMS_RELEASE_KEY ??
  path.join(os.homedir(), '.config', 'neuro-canvas-lms', 'release-signing-key.pem');

if (import.meta.url === `file://${process.argv[1]}`) {
  if (fs.existsSync(KEY_PATH)) {
    console.error(`A signing key already exists at ${KEY_PATH}; refusing to overwrite it.`);
    process.exit(1);
  }
  const { publicKey, privateKey } = generateKeyPairSync('ed25519');
  fs.mkdirSync(path.dirname(KEY_PATH), { recursive: true, mode: 0o700 });
  fs.writeFileSync(KEY_PATH, privateKey.export({ type: 'pkcs8', format: 'pem' }), { mode: 0o600 });
  const raw = Buffer.from(publicKey.export({ format: 'jwk' }).x, 'base64url').toString('base64');
  fs.writeFileSync(
    new URL('../updater/release-public-key.mjs', import.meta.url),
    `// Ed25519 public key of the Neuro-CanvasLMS release signer (generated by scripts/keygen.mjs).\n` +
      `// The updater installs only releases whose manifest is signed by the matching private key.\n` +
      `export const RELEASE_PUBLIC_KEY = '${raw}';\n`,
  );
  console.log(`Private key: ${KEY_PATH} (keep it secret, back it up)`);
  console.log('Public key written to updater/release-public-key.mjs — commit that file.');
}
